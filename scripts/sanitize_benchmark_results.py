#!/usr/bin/env python3
"""Sanitize private Miracast benchmark runs into crowdsource-safe docs.

Reads ``docs/benchmarks/private/*.json`` (gitignored; may contain MAC/SSID),
writes ``docs/benchmarks/public/*.json``, and refreshes the crowdsource table
in ``BENCHMARKS.md`` between:

  <!-- crowdsource-benchmarks:begin -->
  ...
  <!-- crowdsource-benchmarks:end -->

Usage:
  ./scripts/sanitize_benchmark_results.py
  ./scripts/sanitize_benchmark_results.py --dry-run
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

_SCRIPTS = Path(__file__).resolve().parent
if str(_SCRIPTS) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS))

from benchmark_privacy import (  # noqa: E402
    BENCH_DIR,
    PRIVATE_DIR,
    PUBLIC_DIR,
    load_json,
    sanitize_private_run,
    write_json,
)

MARK_BEGIN = "<!-- crowdsource-benchmarks:begin -->"
MARK_END = "<!-- crowdsource-benchmarks:end -->"
BENCHMARKS_MD = Path(__file__).resolve().parents[1] / "BENCHMARKS.md"


def _fmt(value: Any) -> str:
    if value is None or value == "":
        return "—"
    if isinstance(value, float):
        return f"{value:g}"
    if isinstance(value, bool):
        return "yes" if value else "no"
    return str(value)


def _row(pub: dict[str, Any]) -> list[str]:
    sink = pub.get("sink") or {}
    host = pub.get("host") or {}
    session = pub.get("session") or {}
    metrics = pub.get("metrics") or {}
    wifi = host.get("wifi") or {}
    brand = sink.get("manufacturer") or "—"
    model = sink.get("model_code") or sink.get("model_hint") or sink.get("model_name") or "—"
    if model == "—" and sink.get("product_line"):
        model = sink.get("product_line")
    if model == "—" and sink.get("display_name") and sink.get("display_name") != brand:
        disp = str(sink.get("display_name"))
        if disp.strip(" []()_-").lower() != str(brand).lower():
            model = disp
    stream = session.get("stream_mode") or "—"
    path = session.get("capture_path") or "—"
    enc = session.get("encoder") or "—"
    hypr = metrics.get("hyprland_pct_one_core")
    tx = metrics.get("p2p_tx_kbps")
    sta = metrics.get("sta_channel")
    p2p = metrics.get("p2p_channel")
    cpu = (host.get("cpu") or "—")
    if isinstance(cpu, str) and len(cpu) > 42:
        cpu = cpu[:39] + "…"
    return [
        _fmt(pub.get("ts", "")[:10]),
        f"{brand} / {model}",
        _fmt(stream),
        f"{path}/{enc}",
        _fmt(hypr),
        _fmt(tx),
        f"{_fmt(sta)}/{_fmt(p2p)}",
        cpu,
        _fmt(wifi.get("driver")),
        _fmt(pub.get("kind")),
    ]


def render_markdown_table(public_rows: list[dict[str, Any]]) -> str:
    headers = [
        "Date",
        "Sink (mfr / model)",
        "Stream",
        "Capture",
        "Hyprland %",
        "P2P TX kbps",
        "STA/P2P ch",
        "Host CPU",
        "Wi‑Fi driver",
        "Kind",
    ]
    lines = [
        "<!-- Generated by scripts/sanitize_benchmark_results.py — do not edit by hand. -->",
        "",
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for pub in sorted(public_rows, key=lambda r: str(r.get("ts") or ""), reverse=True):
        lines.append("| " + " | ".join(_row(pub)) + " |")
    if len(public_rows) == 0:
        lines.append("| — | — | — | — | — | — | — | — | — | — |")
    lines.append("")
    lines.append(
        "Private full dumps (name, MAC, SSIDs) live in `docs/benchmarks/private/` "
        "(gitignored). Contributors: run a bench, then "
        "`./scripts/sanitize_benchmark_results.py` and PR the updated "
        "`docs/benchmarks/public/` files plus this table."
    )
    return "\n".join(lines) + "\n"


def update_benchmarks_md(table_md: str, dry_run: bool = False) -> None:
    text = BENCHMARKS_MD.read_text(encoding="utf-8")
    if MARK_BEGIN not in text or MARK_END not in text:
        raise SystemExit(
            f"{BENCHMARKS_MD} missing {MARK_BEGIN} / {MARK_END} markers"
        )
    before, rest = text.split(MARK_BEGIN, 1)
    _, after = rest.split(MARK_END, 1)
    new_text = before + MARK_BEGIN + "\n" + table_md + MARK_END + after
    if dry_run:
        print(table_md)
        return
    BENCHMARKS_MD.write_text(new_text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--dry-run", action="store_true")
    args = p.parse_args(argv)

    PRIVATE_DIR.mkdir(parents=True, exist_ok=True)
    PUBLIC_DIR.mkdir(parents=True, exist_ok=True)

    public_rows: list[dict[str, Any]] = []
    for path in sorted(PRIVATE_DIR.glob("*.json")):
        private = load_json(path)
        private.setdefault("stem", path.stem)
        pub = sanitize_private_run(private)
        public_rows.append(pub)
        out = PUBLIC_DIR / f"{pub['id']}.json"
        if not args.dry_run:
            write_json(out, pub)
            print(f"wrote {out.relative_to(BENCH_DIR.parent.parent)}")
        else:
            print(f"dry-run would write {out.name}")

    # Also keep any hand-curated public files not tied to private stems.
    for path in sorted(PUBLIC_DIR.glob("*.json")):
        try:
            row = load_json(path)
        except Exception:
            continue
        if not any(r.get("id") == row.get("id") for r in public_rows):
            public_rows.append(row)

    table = render_markdown_table(public_rows)
    update_benchmarks_md(table, dry_run=args.dry_run)
    if not args.dry_run:
        print(f"updated {BENCHMARKS_MD.relative_to(BENCH_DIR.parent.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
